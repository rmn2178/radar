/**
 * Generates supabase/seed/initial-radar-content.sql from the verified seed in
 * src/data/seed.ts. Idempotent: ON CONFLICT (id) DO NOTHING. Every record is
 * Zod-validated before it reaches SQL, so the seed can never introduce a shape
 * the CMS would reject.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { seedData, seedCollections } from '../src/data/seed';
import { recordSchema } from '../src/lib/content';

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return value === null || value === undefined ? 'null' : sqlString(JSON.stringify(value));
}

const lines: string[] = [
  '-- RADAR Centre initial content. Generated by scripts/generate-seed.ts.',
  '-- Source: verified activity summary supplied with the website briefs.',
  '-- Idempotent: safe to re-run; existing records are never overwritten.',
  'begin;',
];

let count = 0;
for (const collection of seedCollections) {
  for (const record of seedData[collection]) {
    const { title, slug, status, display_order, is_featured, data } = record;
    const parsed = recordSchema(collection).safeParse({ title, slug, status, display_order, is_featured, data });
    if (!parsed.success) {
      console.error(`FAIL seed validation: ${collection}/${slug}`);
      for (const issue of parsed.error.issues) console.error(`  ${issue.path.join('.')}: ${issue.message}`);
      process.exit(1);
    }
    lines.push(
      `insert into public.${collection} (id, title, slug, status, display_order, is_featured, data, published_data) values (` +
      `${sqlString(record.id)}, ${sqlString(title)}, ${sqlString(slug)}, ${sqlString(status)}, ${display_order}, ${is_featured}, ${sqlJson(data)}, ${sqlJson(record.published_data ?? null)}) ` +
      'on conflict (id) do nothing;',
    );
    count += 1;
  }
}
lines.push('commit;', '');

const target = join(process.cwd(), 'supabase', 'seed');
mkdirSync(target, { recursive: true });
const file = join(target, 'initial-radar-content.sql');
writeFileSync(file, lines.join('\n'), 'utf8');
console.log(`PASS seed validation: ${count} records across ${seedCollections.length} collections`);
console.log(`Wrote ${file}`);